//! Routes for admin.

use super::handlers;
use crate::api::MAX_MEDIA_UPLOAD_BYTES;
use crate::state::AppState;
use axum::extract::DefaultBodyLimit;
use axum::routing::{get, post};
use axum::Router;

pub fn session_routes() -> Router<AppState> {
    Router::new()
        .route("/{session_id}/cloud/waba", get(handlers::get_waba))
        .route(
            "/{session_id}/cloud/owned-wabas",
            get(handlers::owned_wabas),
        )
        .route(
            "/{session_id}/cloud/client-wabas",
            get(handlers::client_wabas),
        )
        .route(
            "/{session_id}/cloud/business-portfolio",
            get(handlers::business_portfolio),
        )
        .route(
            "/{session_id}/cloud/phone-numbers",
            get(handlers::list_phone_numbers),
        )
        .route(
            "/{session_id}/cloud/phone-number",
            get(handlers::get_phone_number),
        )
        .route(
            "/{session_id}/cloud/register",
            post(handlers::register_phone),
        )
        .route(
            "/{session_id}/cloud/deregister",
            post(handlers::deregister_phone),
        )
        .route(
            "/{session_id}/cloud/request-code",
            post(handlers::request_code),
        )
        .route(
            "/{session_id}/cloud/verify-code",
            post(handlers::verify_code),
        )
        .route(
            "/{session_id}/cloud/two-step-pin",
            post(handlers::set_two_step_pin),
        )
        .route(
            "/{session_id}/cloud/debug-token",
            get(handlers::debug_token),
        )
        .route(
            "/{session_id}/cloud/business-profile",
            get(handlers::get_business_profile).post(handlers::update_business_profile),
        )
        .route(
            "/{session_id}/cloud/business-profile/photo",
            post(handlers::upload_business_profile_photo)
                .layer(DefaultBodyLimit::max(MAX_MEDIA_UPLOAD_BYTES)),
        )
        .route("/{session_id}/cloud/typing", post(handlers::send_typing))
        .route(
            "/{session_id}/cloud/subscribed-apps",
            get(handlers::list_subscribed_apps)
                .post(handlers::subscribe_app)
                .delete(handlers::unsubscribe_app),
        )
        .route(
            "/{session_id}/cloud/templates",
            get(handlers::list_templates)
                .post(handlers::create_template)
                .delete(handlers::delete_template),
        )
        .route(
            "/{session_id}/cloud/templates/namespace",
            get(handlers::template_namespace),
        )
        .route(
            "/{session_id}/cloud/templates/{template_id}",
            get(handlers::get_template).post(handlers::edit_template),
        )
        .route(
            "/{session_id}/cloud/qr-codes",
            get(handlers::list_qr_codes).post(handlers::create_qr_code),
        )
        .route(
            "/{session_id}/cloud/qr-codes/{code}",
            get(handlers::get_qr_code)
                .post(handlers::update_qr_code)
                .delete(handlers::delete_qr_code),
        )
        .route(
            "/{session_id}/cloud/blocked-users",
            get(handlers::list_blocked_users)
                .post(handlers::block_users)
                .delete(handlers::unblock_users),
        )
        .route(
            "/{session_id}/cloud/business-compliance",
            get(handlers::get_business_compliance).post(handlers::set_business_compliance),
        )
        .route("/{session_id}/cloud/analytics", get(handlers::analytics))
        .route(
            "/{session_id}/cloud/conversation-analytics",
            get(handlers::conversation_analytics),
        )
        .route(
            "/{session_id}/cloud/credit-lines",
            get(handlers::credit_lines),
        )
        .route(
            "/{session_id}/cloud/credit-lines/{credit_line_id}/allocations",
            get(handlers::credit_line_allocations),
        )
        .route(
            "/{session_id}/cloud/credit-sharing",
            post(handlers::share_credit_line),
        )
        .route(
            "/{session_id}/cloud/credit-sharing/{allocation_config_id}",
            get(handlers::get_credit_sharing).delete(handlers::revoke_credit_sharing),
        )
        .route(
            "/{session_id}/cloud/assigned-users",
            get(handlers::list_assigned_users).post(handlers::assign_user),
        )
        .route(
            "/{session_id}/cloud/system-users",
            get(handlers::list_system_users),
        )
        .route(
            "/{session_id}/cloud/flows/{flow_id}/metrics",
            get(handlers::flow_metrics),
        )
        .route(
            "/{session_id}/cloud/flow-endpoint/public-key",
            get(handlers::flow_public_key),
        )
        .route(
            "/{session_id}/cloud/flows-migrate",
            post(handlers::migrate_flows),
        )
        .route(
            "/{session_id}/messages/order-details",
            post(handlers::send_order_details),
        )
        .route(
            "/{session_id}/messages/order-status",
            post(handlers::send_order_status),
        )
}
